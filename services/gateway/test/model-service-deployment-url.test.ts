/**
 * SAP_DEPLOYMENT_URL_BASE (CI relay): getModels moves each deployment's deploymentUrl under the base,
 * for deployments of a foundation model and for deployments of a model the catalogue does not list.
 * Unset, the URL SAP returned is carried unchanged. The module reads its configuration at load time
 * and caches the built list, so each case loads a fresh module registry (same pattern as
 * model-service-unroutable.test.ts).
 */
import { describe, it, expect, jest, afterEach } from '@jest/globals';

export {};

const FOUNDATION_URL = '/lm/scenarios/foundation-models/models';
const SAP_URL_1 = 'https://api.ai.example.test/v2/inference/deployments/d1';
const SAP_URL_2 = 'https://api.ai.example.test/v2/inference/deployments/d2';
const BASE = 'https://relay.example.test/k3y/api';

const FOUNDATION_MODELS = [{
  model: 'openai--gpt-4o',
  provider: 'openai',
  executableId: 'aicore-openai',
  createdAt: '2026-01-01T00:00:00Z',
  allowedScenarios: [{ scenarioId: 'orchestration', executableId: 'orchestration' }],
  versions: [{ name: '1', isLatest: true, streamingSupported: true }]
}];

const deployment = (id: string, modelName: string, deploymentUrl: string) => ({
  id,
  status: 'RUNNING',
  scenarioId: 'foundation-models',
  configurationId: `c-${id}`,
  configurationName: `${modelName}_autogenerated`,
  deploymentUrl,
  details: { resources: { backendDetails: { model: { name: modelName, version: 'latest' } } } }
});

const DEPLOYMENTS = [
  deployment('d1', 'openai--gpt-4o', SAP_URL_1),            // model is in the foundation list
  deployment('d2', 'acme--not-in-catalogue', SAP_URL_2)     // model is not
];

function loadModelService(base: string | undefined) {
  jest.resetModules();
  process.env.AUTH_URL = 'https://auth.example/oauth/token';
  process.env.CLIENT_ID = 'id';
  process.env.CLIENT_SECRET = 'secret';
  process.env.SAP_INCLUDE_EXTENDED_MODEL_ATTRIBUTES = 'true';
  if (base === undefined) delete process.env.SAP_DEPLOYMENT_URL_BASE;
  else process.env.SAP_DEPLOYMENT_URL_BASE = base;

  const get = jest.fn((url: unknown) =>
    Promise.resolve(String(url).includes(FOUNDATION_URL)
      ? { data: { resources: FOUNDATION_MODELS } }
      : { data: { resources: DEPLOYMENTS } }));
  const axiosMock = {
    get,
    post: jest.fn(() => Promise.resolve({ data: { access_token: 't', expires_in: 3600 } }))
  };
  jest.doMock('axios', () => ({ __esModule: true, default: axiosMock, ...axiosMock }));
  jest.doMock('@libs/logger', () => ({
    getDefaultLogger: () => ({ debug: () => undefined, info: () => undefined, warn: () => undefined, error: () => undefined })
  }));
  jest.doMock('../src/services/configService', () => ({
    __esModule: true,
    default: {
      getSAPAICoreConfig: () => ({ url: 'https://ai.example' }),
      getModelListChanges: () => ({})
    }
  }));
  // eslint-disable-next-line @typescript-eslint/no-var-requires
  return require('../src/services/modelService');
}

const urlsById = (list: { data: Array<{ id: string; deploymentUrl?: string }> }) =>
  Object.fromEntries(list.data.filter(m => m.id.endsWith('--deployed')).map(m => [m.id, m.deploymentUrl]));

describe('getModels and SAP_DEPLOYMENT_URL_BASE', () => {
  afterEach(() => {
    delete process.env.SAP_DEPLOYMENT_URL_BASE;
  });

  it('moves the deployment URL of both a catalogue model and an unlisted model under the base', async () => {
    const service = loadModelService(BASE);
    expect(urlsById(await service.getModels(true))).toEqual({
      'openai--gpt-4o--deployed': 'https://relay.example.test/k3y/api/v2/inference/deployments/d1',
      'acme--not-in-catalogue--deployed': 'https://relay.example.test/k3y/api/v2/inference/deployments/d2'
    });
  });

  it('carries the URL SAP returned when the base is not set', async () => {
    const service = loadModelService(undefined);
    expect(urlsById(await service.getModels(true))).toEqual({
      'openai--gpt-4o--deployed': SAP_URL_1,
      'acme--not-in-catalogue--deployed': SAP_URL_2
    });
  });
});
