#!/usr/bin/env node
/**
 * Writes the configuration form's field texts into the config-app bundles (dev tool, not shipped).
 *
 *   node ci/scripts/schema-texts.js           write the bundles
 *   node ci/scripts/schema-texts.js --check   exit 1 when a bundle is not up to date (writes nothing)
 *   node ci/scripts/schema-texts.js --apply <lang> <map.json>
 *                                             fill <lang>'s placeholders from a { "<English>": "<translation>" } map
 *   node ci/scripts/schema-texts.js --accept  record the current English as checked by all six languages
 *                                             (first warns, by language, about changed keys still in English)
 *
 * The form (services/admin/app/config-app/webapp/model/schemaTexts.ts) reads every field label,
 * title and description from the config-app bundle under `schema.<path>.label` /
 * `schema.<path>.description`, with the schema's English as the fallback. This walks
 * services/admin/src/schemas/api-config-schema.json with the same path rules and writes:
 *
 * - i18n.properties and i18n_en.properties: every key with the exact English the form shows (the
 *   schema `title`, else the label derived from the property key, and the `description`) -
 *   regenerated on every run, so a changed schema text changes the English here too;
 * - i18n_de/es/fr/it/nl/pt.properties: every missing key with the ENGLISH value as a placeholder to
 *   translate. An existing value is never overwritten; a key the schema no longer has is removed.
 *
 * The keys sit in one generated block at the end of each file, in schema order. Running it twice
 * changes nothing the second time. A language value that still equals the PREVIOUS English of its
 * key (an untouched placeholder) follows a reworded English, so a placeholder never shows stale text.
 * A new schema field therefore needs: run this, translate the placeholders it added to the six
 * language files, then `--accept`. `app/config-app/test/schemaTexts.test.ts` fails until the default
 * bundle carries the field's keys with the schema's English, and until the translation lock
 * (app/config-app/test/schemaTexts.translated.json: key -> first 12 hex digits of the sha256 of the
 * English the six languages were checked against) matches every key - so a new or reworded English
 * fails until its translations are (re)checked and `--accept` records it.
 *
 * Path rules (keep in step with schemaTexts.ts; the test holds the two together): document path
 * below `api_config`, segments joined with `.`; any key of an `additionalProperties`/
 * `patternProperties` map is `_entry` (an entry has a description key, no label key - its label is
 * its key); any element of an array is `items`; composing `allOf` branches fold into the node as the
 * form folds them (own property first, then the first branch declaring it); conditional `if`/`then`
 * branches add nothing. A path that would get two different English texts is an error.
 */
'use strict';

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const REPO_ROOT = path.resolve(__dirname, '..', '..');
const SCHEMA_FILE = path.join(REPO_ROOT, 'services', 'admin', 'src', 'schemas', 'api-config-schema.json');
const BUNDLE_DIR = path.join(REPO_ROOT, 'services', 'admin', 'app', 'config-app', 'webapp', 'i18n');
const LOCK_FILE = path.join(REPO_ROOT, 'services', 'admin', 'app', 'config-app', 'test', 'schemaTexts.translated.json');
const ENGLISH_FILES = ['i18n.properties', 'i18n_en.properties'];
const LANGUAGE_FILES = ['de', 'es', 'fr', 'it', 'nl', 'pt'].map(lang => `i18n_${lang}.properties`);
const HEADER = [
  '# Configuration form field texts by schema path - generated by ci/scripts/schema-texts.js.',
  '# English is regenerated from the schema; other languages are translated in place and kept.'
];
const ENTRY_SEGMENT = '_entry';
const ITEMS_SEGMENT = 'items';
const SEGMENT = /^[A-Za-z0-9_-]+$/;

// --- the form's own label derivation (schemaForm.ts `labelFor`; the test compares the two) -------

const ACRONYMS = { api: 'API', id: 'ID', url: 'URL', json: 'JSON', dcr: 'DCR', siem: 'SIEM' };

function humanize(key) {
  return key
    .split('_')
    .filter(word => word.length > 0)
    .map(word => ACRONYMS[word.toLowerCase()] ?? word.charAt(0).toUpperCase() + word.slice(1))
    .join(' ');
}

function labelFor(key) {
  return humanize(key.replace(/_env$/, ''));
}

// --- the walk ------------------------------------------------------------------------------------

function isObject(value) {
  return value !== null && typeof value === 'object' && !Array.isArray(value);
}

function resolvePointer(root, ref) {
  if (!ref.startsWith('#/')) return undefined;
  let cursor = root;
  for (const raw of ref.slice(2).split('/')) {
    const segment = raw.replace(/~1/g, '/').replace(/~0/g, '~');
    if (!isObject(cursor)) return undefined;
    cursor = cursor[segment];
  }
  return cursor;
}

/** schemaForm.ts `resolveRef`: follows a chain of `$ref`s, stopping at a repeat or a dangling one. */
function resolveRef(node, root, seen = new Set()) {
  if (!isObject(node) || typeof node.$ref !== 'string' || seen.has(node.$ref)) return node;
  seen.add(node.$ref);
  const target = resolvePointer(root, node.$ref);
  return target ? resolveRef(target, root, seen) : node;
}

/** schemaForm.ts `composeAllOf`, as far as texts go: which properties a node shows, and in what order. */
function composeAllOf(node, root) {
  const branches = isObject(node) && Array.isArray(node.allOf) ? node.allOf : [];
  const composing = branches.filter(branch => isObject(branch) && !branch.if && !branch.then);
  if (composing.length === 0) return node;
  const properties = { ...(node.properties ?? {}) };
  for (const branch of composing) {
    const resolved = composeAllOf(resolveRef(branch, root), root);
    for (const key of Object.keys(resolved.properties ?? {})) {
      if (!Object.prototype.hasOwnProperty.call(properties, key)) properties[key] = resolved.properties[key];
    }
  }
  return { ...node, properties };
}

/** The value schemas of a map node: each `patternProperties` value, then a schema-valued `additionalProperties`. */
function entrySchemas(node) {
  const out = Object.values(isObject(node.patternProperties) ? node.patternProperties : {});
  if (isObject(node.additionalProperties)) out.push(node.additionalProperties);
  return out;
}

function nonEmptyString(value) {
  return typeof value === 'string' && value.length > 0 ? value : undefined;
}

/**
 * Every field text of `schema`, in schema order, as [key, English] pairs. Throws on a property name
 * that cannot be a key segment and on a path that would carry two different English texts.
 */
function collectSchemaTexts(schema) {
  const texts = new Map();
  const put = (key, english) => {
    if (texts.has(key) && texts.get(key) !== english) {
      throw new Error(`schema-texts: "${key}" would carry two different English texts:\n  ${texts.get(key)}\n  ${english}`);
    }
    texts.set(key, english);
  };
  const child = (base, segment) => (base ? `${base}.${segment}` : segment);

  const walk = (raw, at, seen) => {
    if (!isObject(raw)) return;
    if (typeof raw.$ref === 'string') {
      if (seen.has(raw.$ref)) return;
      seen = new Set(seen).add(raw.$ref);
    }
    const node = composeAllOf(resolveRef(raw, schema), schema);
    if (!isObject(node)) return;

    const properties = isObject(node.properties) ? node.properties : {};
    for (const key of Object.keys(properties)) {
      if (!SEGMENT.test(key) || key === ENTRY_SEGMENT) {
        throw new Error(`schema-texts: property "${key}" under "${at || 'api_config'}" cannot be a key segment ([A-Za-z0-9_-], not "${ENTRY_SEGMENT}")`);
      }
      const property = properties[key];
      const keyPath = child(at, key);
      put(`schema.${keyPath}.label`, nonEmptyString(isObject(property) ? property.title : undefined) || labelFor(key));
      const description = nonEmptyString(composeAllOf(resolveRef(property, schema), schema)?.description);
      if (description) put(`schema.${keyPath}.description`, description);
      walk(property, keyPath, seen);
    }

    for (const value of entrySchemas(node)) {
      const entryPath = child(at, ENTRY_SEGMENT);
      const description = nonEmptyString(composeAllOf(resolveRef(value, schema), schema)?.description);
      if (description) put(`schema.${entryPath}.description`, description);
      walk(value, entryPath, seen);
    }

    if (isObject(node.items)) {
      if (Object.prototype.hasOwnProperty.call(properties, ITEMS_SEGMENT)) {
        throw new Error(`schema-texts: "${at}" declares both a property "items" and array items`);
      }
      walk(node.items, child(at, ITEMS_SEGMENT), seen);
    }
  };

  const apiConfig = isObject(schema.properties) ? schema.properties.api_config : undefined;
  walk(apiConfig ?? schema, '', new Set());
  return [...texts];
}

// --- the bundles ---------------------------------------------------------------------------------

/** A .properties value, escaped so UI5's parser reads back exactly `value`. */
function escapeValue(value) {
  return value
    .replace(/\\/g, '\\\\')
    .replace(/\n/g, '\\n')
    .replace(/\r/g, '\\r')
    .replace(/\t/g, '\\t')
    .replace(/^ /, '\\ ');
}

/** True when the line ends in an odd number of backslashes, i.e. continues on the next line. */
function continues(line) {
  const match = /\\+$/.exec(line);
  return match !== null && match[0].length % 2 === 1;
}

/**
 * Splits a bundle into its own lines (everything but the generated block) and the generated keys'
 * existing raw entries (the key's line plus any continuation lines, verbatim).
 */
function splitBundle(text) {
  const lines = text.split('\n');
  const own = [];
  const existing = new Map();
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (HEADER.includes(line)) continue;
    const match = /^\s*(schema\.[A-Za-z0-9_.-]+)\s*[=:]/.exec(line);
    if (!match) {
      own.push(line);
      continue;
    }
    const raw = [line];
    while (continues(raw[raw.length - 1]) && i + 1 < lines.length) raw.push(lines[++i]);
    existing.set(match[1], raw.join('\n'));
  }
  while (own.length > 0 && own[own.length - 1].trim() === '') own.pop();
  return { own, existing };
}

/** The value of one raw entry (its key line plus continuation lines), as UI5's parser reads it. */
function parseValue(raw) {
  const lines = raw.split('\n');
  let joined = lines[0];
  for (let i = 1; i < lines.length; i++) joined = joined.slice(0, -1) + lines[i].replace(/^\s+/, '');
  const value = joined.replace(/^\s*schema\.[A-Za-z0-9_.-]+\s*[=:]\s*/, '');
  return value.replace(/\\(u[0-9a-fA-F]{4}|.)/g, (_all, c) =>
    c.length === 5 ? String.fromCharCode(parseInt(c.slice(1), 16))
      : c === 'n' ? '\n' : c === 't' ? '\t' : c === 'r' ? '\r' : c === 'f' ? '\f' : c);
}

/** Every generated key's value in a bundle, as UI5 reads it. */
function bundleValues(text) {
  const values = new Map();
  for (const [key, raw] of splitBundle(text).existing) values.set(key, parseValue(raw));
  return values;
}

/**
 * True for a language value that is still the placeholder of an English that has since changed:
 * it equals what the default bundle said for the key before this run, and that is not the English now.
 */
function stalePlaceholder(key, value, english, previousEnglish) {
  return previousEnglish.has(key) && previousEnglish.get(key) !== english && value === previousEnglish.get(key);
}

/** English -> the first translation a language file already holds for it (a value differing from it). */
function knownTranslations(existing, entries, previousEnglish) {
  const out = new Map();
  for (const [key, english] of entries) {
    if (!existing.has(key) || out.has(english)) continue;
    const value = parseValue(existing.get(key));
    if (value !== english && !stalePlaceholder(key, value, english, previousEnglish)) out.set(english, value);
  }
  return out;
}

/**
 * The bundle with its generated block rewritten for `entries`. `keepExisting` (the language files)
 * keeps each key's value, except one still holding the key's `previousEnglish` (the default bundle's
 * English before this run) after that English changed: like a missing key, it gets the file's
 * translation of the new English, else the new English.
 */
function renderBundle(text, entries, keepExisting, previousEnglish = new Map()) {
  const { own, existing } = splitBundle(text);
  const known = keepExisting ? knownTranslations(existing, entries, previousEnglish) : new Map();
  const block = entries.map(([key, english]) => {
    if (keepExisting && existing.has(key) && !stalePlaceholder(key, parseValue(existing.get(key)), english, previousEnglish)) {
      return existing.get(key);
    }
    return `${key}=${escapeValue(known.has(english) ? known.get(english) : english)}`;
  });
  return own.concat('', HEADER, block).join('\n') + '\n';
}

// --- the translation lock ------------------------------------------------------------------------

function lockHash(english) {
  return crypto.createHash('sha256').update(english, 'utf8').digest('hex').slice(0, 12);
}

/** The lock file's text for `entries`: key -> hash of its English, in generator order. */
function renderLock(entries) {
  return JSON.stringify(Object.fromEntries(entries.map(([key, english]) => [key, lockHash(english)])), null, 2) + '\n';
}

/** One message per key whose English the six languages have not been checked against. */
function lockProblems(entries, lock) {
  const problems = [];
  for (const [key, english] of entries) {
    if (!Object.prototype.hasOwnProperty.call(lock, key)) {
      problems.push(`${key}: new field: translate in de..nl, then run --accept`);
    } else if (lock[key] !== lockHash(english)) {
      problems.push(`${key}: English reworded: re-check the six translations, then run --accept`);
    }
  }
  const current = new Set(entries.map(([key]) => key));
  for (const key of Object.keys(lock)) {
    if (!current.has(key)) problems.push(`${key}: no longer in the schema: run --accept`);
  }
  return problems;
}

/**
 * The keys about to be accepted (new, or English reworded since the lock) whose value in a language
 * file still equals the English (or that the file lacks), as [lang, keys] in LANGUAGE_FILES order,
 * languages without such keys left out. `languageTexts` maps a language code to its bundle text.
 * Keys the lock already holds with this English are not listed: their identical values were checked.
 */
function untranslatedPlaceholders(entries, lock, languageTexts) {
  const changed = entries.filter(([key, english]) => lock[key] !== lockHash(english));
  const groups = [];
  for (const lang of Object.keys(languageTexts)) {
    const values = bundleValues(languageTexts[lang]);
    const keys = changed.filter(([key, english]) => !values.has(key) || values.get(key) === english).map(([key]) => key);
    if (keys.length > 0) groups.push([lang, keys]);
  }
  return groups;
}

/** The warning lines for untranslatedPlaceholders' groups (none when there are none). */
function placeholderWarning(groups) {
  if (groups.length === 0) return [];
  const total = groups.reduce((sum, [, keys]) => sum + keys.length, 0);
  return [`schema-texts: warning: ${total} changed values still read as English (accepted anyway; fine where identical by design):`]
    .concat(groups.map(([lang, keys]) => `  ${lang} (${keys.length}): ${keys.join(', ')}`));
}

/**
 * Writes the lock from the default bundle; refuses while a bundle is not up to date. Before writing,
 * warns about changed keys that still read as English in a language file - a warning, not a refusal,
 * since a product name or a technical term is meant to stay the same.
 */
function accept(entries) {
  const stale = staleBundles(entries);
  if (stale.length > 0) {
    console.error(`schema-texts: --accept needs up-to-date bundles; run node ci/scripts/schema-texts.js first (${stale.join(', ')})`);
    return 1;
  }
  const lock = fs.existsSync(LOCK_FILE) ? JSON.parse(fs.readFileSync(LOCK_FILE, 'utf8')) : {};
  const languageTexts = Object.fromEntries(LANGUAGE_FILES.map(name =>
    [name.slice(5, -11), fs.readFileSync(path.join(BUNDLE_DIR, name), 'utf8')]));
  for (const line of placeholderWarning(untranslatedPlaceholders(entries, lock, languageTexts))) console.warn(line);
  const values = bundleValues(fs.readFileSync(path.join(BUNDLE_DIR, ENGLISH_FILES[0]), 'utf8'));
  const text = renderLock(entries.map(([key]) => [key, values.get(key)]));
  const changed = fs.existsSync(LOCK_FILE) ? lockProblems(entries, lock).length : entries.length;
  fs.writeFileSync(LOCK_FILE, text);
  console.log(`schema-texts: accepted ${entries.length} keys (${changed} changed) in ${path.relative(REPO_ROOT, LOCK_FILE)}`);
  return 0;
}

/**
 * Fills a language bundle's placeholders (values still equal to their English) from `translations`
 * ({ English: translation }). Values that already differ from the English are kept; a translation
 * identical to its English (a product name, a technical term) is counted apart.
 */
function applyTranslations(text, entries, translations) {
  const rendered = renderBundle(text, entries, true);
  const { own, existing } = splitBundle(rendered);
  const counts = { filled: 0, identical: 0, alreadyTranslated: 0, untranslated: 0 };
  const missing = new Set();
  const block = entries.map(([key, english]) => {
    const raw = existing.get(key);
    if (parseValue(raw) !== english) {
      counts.alreadyTranslated++;
      return raw;
    }
    const translation = Object.prototype.hasOwnProperty.call(translations, english) ? translations[english] : undefined;
    if (typeof translation !== 'string' || translation.length === 0) {
      counts.untranslated++;
      missing.add(english);
      return raw;
    }
    if (translation === english) {
      counts.identical++;
      return raw;
    }
    counts.filled++;
    return `${key}=${escapeValue(translation)}`;
  });
  return { text: own.concat('', HEADER, block).join('\n') + '\n', counts, missing: [...missing] };
}

function apply(lang, mapFile, entries) {
  const name = `i18n_${lang}.properties`;
  if (!LANGUAGE_FILES.includes(name)) {
    console.error(`schema-texts: --apply needs one of ${LANGUAGE_FILES.map(f => f.slice(5, -11)).join(', ')}, not "${lang}"`);
    return 2;
  }
  const translations = JSON.parse(fs.readFileSync(path.resolve(mapFile), 'utf8'));
  const file = path.join(BUNDLE_DIR, name);
  const before = fs.readFileSync(file, 'utf8');
  const { text, counts, missing } = applyTranslations(before, entries, translations);
  if (text !== before) fs.writeFileSync(file, text);
  console.log(`schema-texts: ${name}: ${counts.filled} filled, ${counts.identical} the same as the English, ` +
    `${counts.alreadyTranslated} already translated, ` +
    `${counts.untranslated} still English (${missing.length} distinct English with no map entry)`);
  for (const english of missing) console.log(`  no translation: ${JSON.stringify(english)}`);
  return 0;
}

/** The bundles the write mode would change (relative paths); with `write`, also writes them. */
function staleBundles(entries, write = false) {
  const previousEnglish = bundleValues(fs.readFileSync(path.join(BUNDLE_DIR, ENGLISH_FILES[0]), 'utf8'));
  const stale = [];
  for (const name of ENGLISH_FILES.concat(LANGUAGE_FILES)) {
    const file = path.join(BUNDLE_DIR, name);
    const before = fs.readFileSync(file, 'utf8');
    const after = renderBundle(before, entries, !ENGLISH_FILES.includes(name), previousEnglish);
    if (after === before) continue;
    stale.push(path.relative(REPO_ROOT, file));
    if (write) fs.writeFileSync(file, after);
  }
  return stale;
}

function main(argv) {
  const check = argv.includes('--check');
  const schema = JSON.parse(fs.readFileSync(SCHEMA_FILE, 'utf8'));
  const entries = collectSchemaTexts(schema);
  const applyAt = argv.indexOf('--apply');
  if (applyAt >= 0) {
    if (argv.length < applyAt + 3) {
      console.error('schema-texts: usage: --apply <lang> <map.json>');
      return 2;
    }
    return apply(argv[applyAt + 1], argv[applyAt + 2], entries);
  }
  if (argv.includes('--accept')) return accept(entries);
  const stale = staleBundles(entries, !check);
  const labels = entries.filter(([key]) => key.endsWith('.label')).length;
  console.log(`schema-texts: ${entries.length} keys (${labels} labels, ${entries.length - labels} descriptions)`);
  if (stale.length === 0) {
    console.log('schema-texts: every bundle is up to date');
    return 0;
  }
  console.log(`schema-texts: ${check ? 'not up to date' : 'wrote'}: ${stale.join(', ')}`);
  return check ? 1 : 0;
}

module.exports = {
  collectSchemaTexts, labelFor, escapeValue, parseValue, bundleValues, renderBundle, applyTranslations,
  renderLock, lockProblems, untranslatedPlaceholders, placeholderWarning, SCHEMA_FILE, BUNDLE_DIR, LOCK_FILE, HEADER
};

if (require.main === module) {
  process.exitCode = main(process.argv.slice(2));
}
